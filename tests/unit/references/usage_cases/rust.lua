		expected = case[3] or "read",
		query_expected = case[3] or "read",
		refined_expected = case[3],
		kind = case.kind,
	}
end, DESCRIPTORS)

return { filetype = "rust", source = table.concat(lines, "\n") .. "\n", cases = cases }
